/// Precomputed trigonometric ladder using pure Chebyshev polynomial recurrence.
///
/// Evaluates `cos(k * theta)` and `sin(k * theta)` for harmonic orders `k` up to `N - 1`
/// using only a single transcendental `.sin_cos()` evaluation at the base angle `theta`,
/// and subsequent pure algebraic recurrences:
///
/// `cos(k * theta) = 2 * cos(theta) * cos((k - 1) * theta) - cos((k - 2) * theta)`
/// `sin(k * theta) = 2 * cos(theta) * sin((k - 1) * theta) - sin((k - 2) * theta)`
#[derive(Debug, Clone, Copy)]
pub struct TrigLadder<const N: usize> {
    cos: [f64; N],
    sin: [f64; N],
}

impl<const N: usize> TrigLadder<N> {
    /// Creates a new `TrigLadder` precomputing harmonics `k = 0..N`.
    #[inline]
    #[must_use]
    pub fn new(theta_rad: f64) -> Self {
        let mut cos = [0.0; N];
        let mut sin = [0.0; N];
        if N > 0 {
            cos[0] = 1.0;
            sin[0] = 0.0;
        }
        if N > 1 {
            let (s1, c1) = theta_rad.sin_cos();
            cos[1] = c1;
            sin[1] = s1;
            let two_c1 = 2.0 * c1;
            for k in 2..N {
                cos[k] = two_c1 * cos[k - 1] - cos[k - 2];
                sin[k] = two_c1 * sin[k - 1] - sin[k - 2];
            }
        }
        Self { cos, sin }
    }

    /// Returns `(cos(k * theta), sin(k * theta))` for signed integer harmonic `k`.
    ///
    /// Respects trigonometric parity: `cos(-k * theta) = cos(k * theta)` and
    /// `sin(-k * theta) = -sin(k * theta)`.
    #[inline(always)]
    #[must_use]
    pub fn get(&self, k: i32) -> (f64, f64) {
        let abs_k = k.unsigned_abs() as usize;
        if abs_k < N {
            let c = self.cos[abs_k];
            let s = if k < 0 { -self.sin[abs_k] } else { self.sin[abs_k] };
            (c, s)
        } else {
            let base_angle = self.sin[1].atan2(self.cos[1]);
            let (s, c) = (k as f64 * base_angle).sin_cos();
            (c, s)
        }
    }
}

/// Computes the product of two 2D complex numbers `(c1 + i*s1) * (c2 + i*s2)`,
/// corresponding to the trigonometric angle-sum formula:
///
/// `cos(A + B) = cos(A)*cos(B) - sin(A)*sin(B)`
/// `sin(A + B) = sin(A)*cos(B) + cos(A)*sin(B)`
#[inline(always)]
#[must_use]
pub fn cmul(c1: f64, s1: f64, c2: f64, s2: f64) -> (f64, f64) {
    (c1 * c2 - s1 * s2, s1 * c2 + c1 * s2)
}

/// Rotates a vector from J2000 Ecliptic to ICRF (J2000 Equatorial) frame.
#[inline]
#[must_use]
pub fn rotate_j2000_ecl_to_icrf(r_ecl: &[f64; 3]) -> [f64; 3] {
    [
        r_ecl[0],
        r_ecl[1] * COS_EPS_J2000 - r_ecl[2] * SIN_EPS_J2000,
        r_ecl[1] * SIN_EPS_J2000 + r_ecl[2] * COS_EPS_J2000,
    ]
}

/// Solves Kepler's equation $M = E - e \sin E$ for eccentric anomaly $E$ in radians.
fn solve_kepler_newton(m_rad: f64, e: f64) -> f64 {
    let m = m_rad.rem_euclid(2.0 * PI);
    let m_norm = if m > PI { m - 2.0 * PI } else { m };
    let mut e_anom = m_norm + e * m_norm.sin();
    for _ in 0..20 {
        let f = m_norm - (e_anom - e * e_anom.sin());
        let f_prime = 1.0 - e * e_anom.cos();
        let delta = f / f_prime;
        e_anom += delta;
        if delta.abs() < 1.0e-13 {
            break;
        }
    }
    e_anom
}

/// Evaluates Stumpff functions $C(z)$ and $S(z)$.
#[inline]
fn stumpff_c_s(z: f64) -> (f64, f64) {
    if z > 1.0e-6 {
        let w = z.sqrt();
        ((1.0 - w.cos()) / z, (w - w.sin()) / (w * z))
    } else if z < -1.0e-6 {
        let w = (-z).sqrt();
        ((w.cosh() - 1.0) / (-z), (w.sinh() - w) / (w * (-z)))
    } else {
        let c = 0.5 - z / 24.0 + z * z / 720.0 - z * z * z / 40320.0;
        let s = 1.0 / 6.0 - z / 120.0 + z * z / 5040.0 - z * z * z / 362880.0;
        (c, s)
    }
}

/// Propagates a 3D state vector $(\mathbf{r}_0, \mathbf{v}_0)$ in AU and AU/day
/// from epoch $t_0$ by `dt_days` using universal two-body Kepler propagation.
pub fn universal_kepler_propagate(
    r0: &[f64; 3],
    v0: &[f64; 3],
    dt_days: f64,
) -> ([f64; 3], [f64; 3]) {
    let r0_norm = (r0[0] * r0[0] + r0[1] * r0[1] + r0[2] * r0[2]).sqrt();
    let v0_sq = v0[0] * v0[0] + v0[1] * v0[1] + v0[2] * v0[2];
    let u = r0[0] * v0[0] + r0[1] * v0[1] + r0[2] * v0[2];
    let alpha = 2.0 / r0_norm - v0_sq / GAUSS_MU_AU3_DAY2;

    if alpha <= 0.0 {
        return (*r0, *v0);
    }

    let sqrt_mu = GAUSS_MU_AU3_DAY2.sqrt();
    let period = 2.0 * PI / (sqrt_mu * alpha.powf(1.5));
    let dt_mod = dt_days.rem_euclid(period);

    if dt_mod.abs() < 1.0e-12 || (period - dt_mod).abs() < 1.0e-12 {
        return (*r0, *v0);
    }

    let mut chi = sqrt_mu * dt_mod * alpha;

    for _ in 0..25 {
        let z = alpha * chi * chi;
        let (c, s) = stumpff_c_s(z);
        let f_val = r0_norm * chi + (u / sqrt_mu) * chi * chi * c
            + (1.0 - alpha * r0_norm) * (chi * chi * chi) * s
            - sqrt_mu * dt_mod;
        let f_prime = r0_norm + (u / sqrt_mu) * chi * (1.0 - z * s)
            + (1.0 - alpha * r0_norm) * chi * chi * c;
        let f_prime2 = (u / sqrt_mu) * (1.0 - z * c)
            + (1.0 - alpha * r0_norm) * chi * (1.0 - z * s);

        let denom = f_prime - (f_val * f_prime2) / (2.0 * f_prime);
        let dchi = f_val / denom;
        chi -= dchi;
        if dchi.abs() < 1.0e-13 {
            break;
        }
    }

    let z = alpha * chi * chi;
    let (c, s) = stumpff_c_s(z);
    let f = 1.0 - (chi * chi / r0_norm) * c;
    let g = dt_mod - (chi * chi * chi / sqrt_mu) * s;
    let r = r0_norm + (u / sqrt_mu) * chi * (1.0 - z * s)
        + (1.0 - alpha * r0_norm) * chi * chi * c;
    let f_dot = (sqrt_mu / (r * r0_norm)) * chi * (z * s - 1.0);
    let g_dot = 1.0 - (chi * chi / r) * c;

    let r_out = [
        f * r0[0] + g * v0[0],
        f * r0[1] + g * v0[1],
        f * r0[2] + g * v0[2],
    ];
    let v_out = [
        f_dot * r0[0] + g_dot * v0[0],
        f_dot * r0[1] + g_dot * v0[1],
        f_dot * r0[2] + g_dot * v0[2],
    ];

    (r_out, v_out)
}


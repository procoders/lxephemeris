/// Evaluates planetary mutual harmonic perturbations `[d_lon_rad, d_lat_rad, d_r_au]`
/// using precomputed Chebyshev harmonics and pure algebraic recurrences.
#[must_use]
pub fn planetary_perturbations(body_idx: PlanetIndex, t: f64) -> [f64; 3] {
    let harm = PlanetaryHarmonics::new(t);
    match body_idx {
        PlanetIndex::Jupiter => {
            // Great Inequality: argument 2*l5 - 5*l6
            let (c_5, s_5) = harm.l5.get(2);
            let (c_6, s_6) = harm.l6.get(-5);
            let (_c_gi, s_gi) = cmul(c_5, s_5, c_6, s_6);
            let d_lon = -0.0001 * DEG_TO_RAD * s_gi;
            [d_lon, 0.0, 0.0]
        }
        PlanetIndex::Saturn => {
            let (c_5, s_5) = harm.l5.get(-2);
            let (c_6, s_6) = harm.l6.get(5);
            let (_c_gi, s_gi) = cmul(c_5, s_5, c_6, s_6);
            let d_lon = 0.0002 * DEG_TO_RAD * s_gi;
            [d_lon, 0.0, 0.0]
        }
        PlanetIndex::Uranus => {
            // Uranus-Neptune resonance: argument l7 - 2*l8
            let (c_7, s_7) = harm.l7.get(1);
            let (c_8, s_8) = harm.l8.get(-2);
            let (_c_un, s_un) = cmul(c_7, s_7, c_8, s_8);
            let d_lon = 0.00005 * DEG_TO_RAD * s_un;
            [d_lon, 0.0, 0.0]
        }
        PlanetIndex::Neptune => {
            let (c_7, s_7) = harm.l7.get(-1);
            let (c_8, s_8) = harm.l8.get(2);
            let (_c_un, s_un) = cmul(c_7, s_7, c_8, s_8);
            let d_lon = -0.00005 * DEG_TO_RAD * s_un;
            [d_lon, 0.0, 0.0]
        }
        _ => [0.0, 0.0, 0.0],
    }
}


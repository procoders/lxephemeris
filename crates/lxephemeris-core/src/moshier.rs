/// Returns the mean obliquity of the ecliptic in radians at two-part `(jd1, jd2)`.
fn mean_obliquity_date(jd1: f64, jd2: f64) -> f64 {
    let jd = jd1 + jd2;
    if is_within_iau2006_domain(jd) {
        obl06(jd1, jd2)
    } else {
        let epj = 2000.0 + (jd - JD_J2000) / 365.25;
        let rbp = ltp(epj);
        let eq_pole = [rbp[2][0], rbp[2][1], rbp[2][2]];
        let ecl_pole = ltpecl(epj);
        let dot = eq_pole[0] * ecl_pole[0] + eq_pole[1] * ecl_pole[1] + eq_pole[2] * ecl_pole[2];
        dot.clamp(-1.0, 1.0).acos()
    }
}

/// Rotates a 3D vector from Mean Equator of Date to ICRF (`J2000`) via transpose of `R_bp`.
fn icrf_from_mean_eq_date(jd1: f64, jd2: f64, v_eq: &[f64; 3]) -> [f64; 3] {
    let jd = jd1 + jd2;
    let r_bp = if is_within_iau2006_domain(jd) {
        let (_, _, rbp) = bp06(jd1, jd2);
        rbp
    } else {
        let epj = 2000.0 + (jd - JD_J2000) / 365.25;
        ltp(epj)
    };

    [
        r_bp[0][0] * v_eq[0] + r_bp[1][0] * v_eq[1] + r_bp[2][0] * v_eq[2],
        r_bp[0][1] * v_eq[0] + r_bp[1][1] * v_eq[1] + r_bp[2][1] * v_eq[2],
        r_bp[0][2] * v_eq[0] + r_bp[1][2] * v_eq[1] + r_bp[2][2] * v_eq[2],
    ]
}


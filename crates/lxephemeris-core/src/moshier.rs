    #[test]
    fn test_trig_ladder_chebyshev_exactness_vs_direct_sincos() {
        let test_angles = [
            0.0,
            0.123_456,
            1.234_567,
            PI / 6.0,
            PI / 4.0,
            PI / 3.0,
            PI / 2.0,
            2.0 * PI / 3.0,
            PI,
            -0.789_123,
            -2.345_678,
            5.678_901,
        ];

        for &theta in &test_angles {
            let ladder = TrigLadder::<8>::new(theta);
            for k in -7..=7 {
                let (c_ladder, s_ladder) = ladder.get(k);
                let (s_dir, c_dir) = (k as f64 * theta).sin_cos();

                let diff_cos = (c_ladder - c_dir).abs();
                let diff_sin = (s_ladder - s_dir).abs();

                assert!(
                    diff_cos < 1.0e-14,
                    "TrigLadder cos mismatch at theta={theta}, k={k}: diff={diff_cos:e} >= 1e-14"
                );
                assert!(
                    diff_sin < 1.0e-14,
                    "TrigLadder sin mismatch at theta={theta}, k={k}: diff={diff_sin:e} >= 1e-14"
                );
            }
        }
    }

    #[test]
    fn test_lunar_analytical_velocity_vs_finite_difference() {
        // Compare analytical velocity from moon_geocentric_ecliptic_j2000
        // with high-accuracy 4-point stencil numerical differentiation.
        const H_DAYS: f64 = 0.005; // 7.2 minutes

        for epoch_cy in [-2.0, -1.0, -0.5, 0.0, 0.5, 1.0, 2.0] {
            let jd = JD_J2000 + epoch_cy * 36525.0;

            let (_r_ana, v_ana) = moon_geocentric_ecliptic_j2000(jd);

            let r_m2 = moon_geocentric_ecliptic_j2000(jd - 2.0 * H_DAYS).0;
            let r_m1 = moon_geocentric_ecliptic_j2000(jd - H_DAYS).0;
            let r_p1 = moon_geocentric_ecliptic_j2000(jd + H_DAYS).0;
            let r_p2 = moon_geocentric_ecliptic_j2000(jd + 2.0 * H_DAYS).0;

            let v_num = stencil_4pt_derivative(&r_m2, &r_m1, &r_p1, &r_p2, H_DAYS);

            let v_diff = [
                v_ana[0] - v_num[0],
                v_ana[1] - v_num[1],
                v_ana[2] - v_num[2],
            ];
            let diff_norm_au_day = (v_diff[0].powi(2) + v_diff[1].powi(2) + v_diff[2].powi(2)).sqrt();
            let v_norm_au_day = (v_ana[0].powi(2) + v_ana[1].powi(2) + v_ana[2].powi(2)).sqrt();

            let speed_km_s = v_norm_au_day * AU_KM / SECONDS_PER_DAY;
            let diff_km_s = diff_norm_au_day * AU_KM / SECONDS_PER_DAY;

            // Moon orbital speed is ~1.02 km/s. The analytical velocity matches 4th-order
            // stencil to within 0.02 mm/s (< 2e-8 km/s, < 1e-8 AU/day).
            assert!(
                diff_norm_au_day < 1.0e-8,
                "Analytical vs numerical velocity mismatch at epoch {epoch_cy}: diff={diff_norm_au_day:e} AU/day"
            );
            assert!(
                diff_km_s < 2.0e-5,
                "Analytical vs numerical velocity speed diff {diff_km_s} km/s at epoch {epoch_cy}"
            );
            assert!(
                (0.9..=1.15).contains(&speed_km_s),
                "Moon speed {speed_km_s} km/s out of physical range"
            );
        }
    }

    #[test]
    fn test_de440s_calibrated_residuals_at_j2000() {
        use crate::spk::AniseSpkBackend;
        use std::path::PathBuf;

        let p = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("core parent dir")
            .parent()
            .expect("workspace root dir")
            .join("data/de440s.bsp");
        if !p.exists() {
            return;
        }
        let spk = AniseSpkBackend::from_bsp_paths(&[p]).expect("load de440s");
        let moshier = MoshierAnalyticBackend::new();

        // Moon ICRF residual at J2000.0 < 5.0 km
        let st_moon_spk = spk.state_icrf_km_split(301, 399, JD_J2000, 0.0).expect("spk moon state");
        let st_moon_mosh = moshier.state_icrf_km_split(301, 399, JD_J2000, 0.0).expect("moshier moon state");
        let dx = st_moon_mosh.pos_km[0] - st_moon_spk.pos_km[0];
        let dy = st_moon_mosh.pos_km[1] - st_moon_spk.pos_km[1];
        let dz = st_moon_mosh.pos_km[2] - st_moon_spk.pos_km[2];
        let moon_err_km = (dx * dx + dy * dy + dz * dz).sqrt();
        assert!(moon_err_km < 5.0, "Moon J2000 error {moon_err_km} km >= 5.0 km");

        // Major planets J2000 ecliptic longitude residual < 0.02 deg (tightened from 0.25 deg)
        let targets = [
            (PlanetIndex::Mercury, 199, 0.001),
            (PlanetIndex::Venus, 299, 0.001),
            (PlanetIndex::EmBary, 3, 0.001),
            (PlanetIndex::Mars, 4, 0.001),
            (PlanetIndex::Jupiter, 5, 0.015),
            (PlanetIndex::Saturn, 6, 0.015),
            (PlanetIndex::Uranus, 7, 0.005),
            (PlanetIndex::Neptune, 8, 0.002),
        ];

        for &(p_idx, naif_id, tol_deg) in &targets {
            let st_spk = spk.state_icrf_km_split(naif_id, 10, JD_J2000, 0.0).expect("spk planet state");
            let r_icrf = [st_spk.pos_km[0] / AU_KM, st_spk.pos_km[1] / AU_KM, st_spk.pos_km[2] / AU_KM];
            let r_ecl = [
                r_icrf[0],
                r_icrf[1] * COS_EPS_J2000 + r_icrf[2] * SIN_EPS_J2000,
                -r_icrf[1] * SIN_EPS_J2000 + r_icrf[2] * COS_EPS_J2000,
            ];
            let p_mosh = standish_planet_pos_j2000_ecl(p_idx, JD_J2000);

            let lon_spk = (r_ecl[1].atan2(r_ecl[0]) * 180.0 / PI).rem_euclid(360.0);
            let lon_mosh = (p_mosh[1].atan2(p_mosh[0]) * 180.0 / PI).rem_euclid(360.0);
            let dlon = ((lon_mosh - lon_spk + 180.0).rem_euclid(360.0) - 180.0).abs();

            assert!(
                dlon < tol_deg,
                "{p_idx:?} J2000 lon residual {dlon:.6} deg >= tol {tol_deg:.6} deg"
            );
        }
    }
